// firebase emulators:exec --project demo-hr --only firestore,auth "node scripts/test-marketplace.cjs"
process.env.GCLOUD_PROJECT = 'demo-hr';
const fns = require('../functions/index.js');
const core = require('../functions/marketplace-core.js');
const admin = require('../functions/node_modules/firebase-admin');
const db = admin.firestore();
const P = 'artifacts/comayagua-vip-pro-v4/public/data';
const ADMIN = { uid: 'adm', token: { email: 'josuesoza0513@gmail.com', email_verified: true } };
const SEL = { uid: 'sel', token: { email: 'sel@x.com' } };
const OTHER = { uid: 'oth', token: { email: 'oth@x.com' } };
const call = (fn, auth, data) => fns[fn].run({ auth, data, rawRequest: {} });
let pass = 0, fail = 0;
const ok = (n, c) => { if (c) { pass++; console.log('PASS', n); } else { fail++; console.log('FAIL', n); } };
const rejects = async (n, p, code) => { try { await p; ok(n, false); } catch (e) { ok(`${n} (${e.code})`, !code || e.code === code); } };
(async () => {
  ok('core: 10% de 450000 = 45000', core.computeCommission(450000).commission === 45000);
  ok('core: renta semana x2 usa precio semanal', core.resolveClose({ category: 'carros_renta', priceWeek: 7000 }, { period: 'week', units: 2 }).amount === 14000);
  ok('core: renta día comisión 120', core.resolveClose({ category: 'carros_renta', priceDay: 1200 }, { period: 'day' }).commission === 120);
  ok('core: totales', JSON.stringify(core.commissionTotals([{ commission: 10, status: 'paid' }, { commission: 5 }, { commission: 2.5 }])) === JSON.stringify({ pending: 7.5, paid: 10, pendingCount: 2, paidCount: 1 }));
  const L = (o) => ({ ownerUid: 'sel', ownerName: 'Ana', status: 'pending', category: 'carros_venta', title: 'Hilux', price: 450000, city: 'comayagua', whatsapp: '50499998888', photos: ['x'], ...o });
  await db.doc(`${P}/marketplace_listings/v1`).set(L());
  await db.doc(`${P}/marketplace_listings/r1`).set(L({ category: 'carros_renta', price: null, priceDay: 1200, priceWeek: 7000, priceMonth: 25000, status: 'approved' }));
  await rejects('vendedor NO se aprueba', call('marketplaceModerate', SEL, { listingId: 'v1', action: 'approve' }), 'permission-denied');
  await rejects('NO se vende sin aprobar', call('marketplaceMarkClosed', SEL, { listingId: 'v1', amount: 400000 }), 'failed-precondition');
  await call('marketplaceModerate', ADMIN, { listingId: 'v1', action: 'approve' });
  ok('admin aprueba', (await db.doc(`${P}/marketplace_listings/v1`).get()).data().status === 'approved');
  await rejects('otro NO marca vendida', call('marketplaceMarkClosed', OTHER, { listingId: 'v1', amount: 1 }), 'permission-denied');
  const s = await call('marketplaceMarkClosed', SEL, { listingId: 'v1', amount: 430000 });
  ok('venta: comisión 43000 al vendedor', s.commission === 43000 && s.kind === 'sale' && s.sellerNet === 387000);
  const v1 = (await db.doc(`${P}/marketplace_listings/v1`).get()).data();
  ok('venta: queda sold', v1.status === 'sold' && v1.closedAmount === 430000);
  const c1 = (await db.doc(`${P}/marketplace_commissions/${s.commissionId}`).get()).data();
  ok('comisión pending, paidBy seller', c1.status === 'pending' && c1.paidBy === 'seller' && c1.sellerUid === 'sel');
  await rejects('NO se vende dos veces', call('marketplaceMarkClosed', SEL, { listingId: 'v1', amount: 1 }), 'failed-precondition');
  await rejects('renta sin período', call('marketplaceMarkClosed', SEL, { listingId: 'r1' }), 'invalid-argument');
  const r = await call('marketplaceMarkClosed', ADMIN, { listingId: 'r1', period: 'month' });
  ok('renta mes: 10% de 25000 = 2500 (staff)', r.commission === 2500 && r.kind === 'rental' && r.period === 'month');
  const r1 = (await db.doc(`${P}/marketplace_listings/r1`).get()).data();
  ok('renta: sigue publicada, cuenta 1', r1.status === 'approved' && r1.rentalsCount === 1);
  await rejects('vendedor NO marca pagada', call('marketplaceSetCommissionStatus', SEL, { commissionId: s.commissionId }), 'permission-denied');
  await call('marketplaceSetCommissionStatus', ADMIN, { commissionId: s.commissionId });
  ok('admin marca pagada', (await db.doc(`${P}/marketplace_commissions/${s.commissionId}`).get()).data().status === 'paid');
  await call('marketplaceModerate', ADMIN, { listingId: 'r1', action: 'remove', reason: 'prueba' });
  ok('admin quita', (await db.doc(`${P}/marketplace_listings/r1`).get()).data().status === 'removed');
  console.log(`\n${pass}/${pass + fail} PASS`); process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
