// RULES=firestore.rules firebase emulators:exec --project demo-hr --only firestore "node scripts/test-rules-marketplace.mjs"
import fs from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, setDoc, getDoc, updateDoc, deleteDoc, getDocs, query, where, collection } from 'firebase/firestore';
const APP = 'comayagua-vip-pro-v4';
const env = await initializeTestEnvironment({ projectId: 'demo-hr', firestore: { rules: fs.readFileSync(process.env.RULES, 'utf8'), host: '127.0.0.1', port: 8080 } });
const P = `artifacts/${APP}/public/data`;
await env.clearFirestore();
const L = (o = {}) => ({ ownerUid: 'sel', status: 'pending', category: 'carros_venta', title: 'Toyota Hilux 2015', description: 'Bien cuidada', price: 450000, currency: 'HNL', city: 'comayagua', cityName: 'Comayagua', whatsapp: '50499998888', photos: ['https://x/1.jpg'], createdAtMs: 1, updatedAtMs: 1, ...o });
await env.withSecurityRulesDisabled(async (c) => {
  const db = c.firestore();
  await setDoc(doc(db, `artifacts/${APP}/roles/sup`), { role: 'supervisor' });
  await setDoc(doc(db, `${P}/marketplace_listings/ap`), L({ status: 'approved' }));
  await setDoc(doc(db, `${P}/marketplace_listings/pe`), L());
  await setDoc(doc(db, `${P}/marketplace_listings/rj`), L({ status: 'rejected', rejectReason: 'fotos', reviewedBy: 'sup' }));
  await setDoc(doc(db, `${P}/marketplace_commissions/c1`), { sellerUid: 'sel', commission: 45000, status: 'pending' });
});
const cx = (u) => env.authenticatedContext(u, { email: `${u}@x.com` }).firestore();
const anon = env.unauthenticatedContext().firestore();
let pass = 0, fail = 0;
const t = async (n, p, want) => { try { await (want ? assertSucceeds(p) : assertFails(p)); pass++; console.log('PASS', n); } catch (e) { fail++; console.log('FAIL', n, e.message); } };
const LD = (u, id) => doc(cx(u), `${P}/marketplace_listings/${id}`);
await t('sin sesión lee aprobada', getDoc(doc(anon, `${P}/marketplace_listings/ap`)), true);
await t('sin sesión lista aprobadas', getDocs(query(collection(anon, `${P}/marketplace_listings`), where('status', '==', 'approved'))), true);
await t('sin sesión NO lee pendiente', getDoc(doc(anon, `${P}/marketplace_listings/pe`)), false);
await t('otro NO lee pendiente ajena', getDoc(LD('cli', 'pe')), false);
await t('dueño lee su pendiente', getDoc(LD('sel', 'pe')), true);
await t('supervisor lee pendiente', getDoc(LD('sup', 'pe')), true);
await t('usuario publica (pending)', setDoc(LD('cli', 'n1'), L({ ownerUid: 'cli' })), true);
await t('NO publica ya aprobada', setDoc(LD('cli', 'n2'), L({ ownerUid: 'cli', status: 'approved' })), false);
await t('NO publica a nombre de otro', setDoc(LD('cli', 'n3'), L()), false);
await t('NO publica sin fotos', setDoc(LD('cli', 'n4'), L({ ownerUid: 'cli', photos: [] })), false);
await t('NO publica con comisión inventada', setDoc(LD('cli', 'n5'), L({ ownerUid: 'cli', commission: 0 })), false);
await t('renta exige precio diario', setDoc(LD('cli', 'n6'), L({ ownerUid: 'cli', category: 'carros_renta', price: null })), false);
await t('renta con día/semana/mes', setDoc(LD('cli', 'n7'), L({ ownerUid: 'cli', category: 'carros_renta', price: null, priceDay: 1200, priceWeek: 7000, priceMonth: 25000 })), true);
await t('sin sesión NO publica', setDoc(doc(anon, `${P}/marketplace_listings/n8`), L()), false);
await t('dueño edita pendiente', updateDoc(LD('sel', 'pe'), { price: 440000 }), true);
await t('dueño corrige rechazada → pending', updateDoc(LD('sel', 'rj'), { status: 'pending', photos: ['https://x/2.jpg'] }), true);
await t('dueño NO se aprueba solo', updateDoc(LD('sel', 'pe'), { status: 'approved' }), false);
await t('dueño NO edita aprobada', updateDoc(LD('sel', 'ap'), { price: 1 }), false);
await t('dueño NO marca vendida', updateDoc(LD('sel', 'ap'), { status: 'sold' }), false);
await t('supervisor NO aprueba directo (callable)', updateDoc(LD('sup', 'pe'), { status: 'approved' }), false);
await t('nadie borra', deleteDoc(LD('sel', 'pe')), false);
await t('vendedor lee su comisión', getDoc(doc(cx('sel'), `${P}/marketplace_commissions/c1`)), true);
await t('otro NO lee comisión', getDoc(doc(cx('cli'), `${P}/marketplace_commissions/c1`)), false);
await t('supervisor lee comisión', getDoc(doc(cx('sup'), `${P}/marketplace_commissions/c1`)), true);
await t('vendedor NO marca pagada', updateDoc(doc(cx('sel'), `${P}/marketplace_commissions/c1`), { status: 'paid' }), false);
await t('vendedor NO crea comisión', setDoc(doc(cx('sel'), `${P}/marketplace_commissions/c2`), { sellerUid: 'sel', commission: 1 }), false);
console.log(`\n${pass}/${pass + fail} PASS`);
await env.cleanup();
process.exit(fail ? 1 : 0);
